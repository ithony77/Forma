/** Real Chromium integration, isolated local storage and standalone file exports.
 * No provider or external component request is made. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { createApp } from '../server/app.mjs';
import { CATALOG } from '../shared/catalog.mjs';
import { createSpec, makeSection } from '../shared/content.mjs';
import { createExportFiles } from '../shared/export.mjs';
import { BUNDLED_NOTICES } from '../shared/notices.mjs';
import { PNG_IMAGE } from './fixtures/images.mjs';

test('native interactions work in sandboxed Inspect/Interact, library samples and file exports', {skip:!process.env.FORMA_PLAYWRIGHT_MODULE,timeout:120000}, async t => {
  const {chromium}=await import(pathToFileURL(process.env.FORMA_PLAYWRIGHT_MODULE));
  const directory=await mkdtemp(path.join(tmpdir(),'forma-interactions-'));
  const app=await createApp({dataDir:directory,fetchImpl:()=>{throw new Error('No live provider may be called.');}});
  const browser=await chromium.launch({headless:true,...(process.env.FORMA_TEST_BROWSER?{executablePath:process.env.FORMA_TEST_BROWSER}:{})});
  t.after(async()=>{await browser.close();await app.close();await rm(directory,{recursive:true,force:true});});
  const spec=createSpec('Interaction fixture');
  spec.theme.motion='expressive'; spec.theme.font='modern';
  spec.sections=[makeSection('hero','app-dashboard'),makeSection('features','features-spotlight'),makeSection('services','services-reveal'),makeSection('gallery','gallery-stack'),makeSection('process','process-stacked'),makeSection('cta')];
  spec.sections[0].interface.tabStyle='sliding';spec.sections[0].elements.actionMotion='underline';
  spec.sections[1].elements.entrance='rise';spec.sections[5].elements.actionMotion='arrow';
  for (const item of spec.sections[3].items) { item.image=PNG_IMAGE;item.alt='Saved image alternative text'; }
  const saved=await app.store.create(spec);
  await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${app.server.address().port}`;
  const page=await browser.newPage({viewport:{width:2000,height:1100}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.addInitScript(id=>{if(window !== window.top)return;localStorage.setItem('forma:last-project',id);localStorage.setItem('forma:locale','en');},saved.id);
  await page.goto(base);
  // Keep the editor iframe at 1:1 for automation; Playwright's coordinates in a
  // transformed iframe do not reliably target the browser's visible content.
  await page.waitForFunction(() => document.querySelector('#preview-frame').style.transform === 'scale(1)');
  if (await page.locator('#cookie-accept-button').isVisible()) await page.locator('#cookie-accept-button').click();
  const frame=page.frameLocator('#preview-frame');
  await frame.locator('.service-disclosure[open]').first().waitFor();
  assert.equal(await frame.locator('.service-disclosure[open]').count(),3);
  assert.equal(await frame.locator('[data-gallery-item][inert]').count(),0);
  assert.ok(await frame.locator('[data-ui-panel="summary"]').isVisible(),'Inspect exposes authored tab content');
  await page.locator('#inspect-button').click();
  await frame.locator('[data-gallery-enhanced="stack"]').waitFor();
  assert.equal(await frame.locator('.service-disclosure[open]').count(),0,'Inspect restores previous disclosure state');
  await frame.locator('.service-disclosure summary').first().click();
  assert.ok(await frame.locator('.service-disclosure').first().evaluate(node=>node.open));
  await frame.locator('.ui-tabs [role="tab"]').first().focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await frame.locator('.ui-tabs [aria-selected="true"]').getAttribute('data-ui-tab'),'summary');
  assert.ok(await frame.locator('[data-ui-panel="summary"]').isVisible());
  assert.ok(!(await frame.locator('[data-ui-panel="main"]').isVisible()));
  assert.ok(await frame.locator('.ui-tab-indicator').evaluate(node=>node.getBoundingClientRect().width>0));
  await frame.locator('[data-gallery-step="1"]').click();
  assert.equal(await frame.locator('.gallery-position').textContent(),'2 / 3');
  assert.equal(await frame.locator('[data-gallery-item][inert]').count(),2);
  await page.locator('#inspect-button').click();
  await frame.locator('[data-gallery-enhanced="plain"]').waitFor();
  assert.equal(await frame.locator('[data-gallery-item][inert]').count(),0);
  await page.locator('#inspect-button').click();
  await frame.locator('[data-gallery-enhanced="stack"]').waitFor();
  assert.equal(await frame.locator('.gallery-position').textContent(),'2 / 3');
  assert.ok(await frame.locator('.service-disclosure').first().evaluate(node=>node.open));

  const before=await app.store.get(saved.id);
  await page.locator('#explore-interactions-button').click();
  assert.ok(await page.locator('#library-content').isVisible());
  assert.equal(await page.locator('[data-library-filter="interactive"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#library-list [data-add-block]').count(),CATALOG.filter(block=>block.capabilities.interactive||block.capabilities.sources.length).length);
  assert.equal(await page.locator('#library-list .library-icon-group').count(),0);
  await page.locator('#library-search').fill('Watermelon');
  assert.deepEqual(await page.locator('#library-list [data-add-block]').evaluateAll(nodes=>nodes.map(node=>node.dataset.addBlock)),CATALOG.filter(block=>block.source.includes('Watermelon')||block.capabilities.references?.includes('watermelon')).map(block=>block.id));
  await page.locator('#library-search').fill('');
  await page.locator('[data-library-filter="all"]').click();
  assert.equal(await page.locator('#library-list [data-add-block]').count(),105);
  assert.ok(await page.locator('#library-list [data-add-block="features-spotlight"]').isVisible(),'Initial adapted interactions remain discoverable');
  await page.locator('[data-left-tab="brief"]').click();
  await page.locator('[data-left-tab="library"]').click();
  assert.ok(await page.locator('.library-thumbnail i').first().evaluate(node=>node.getBoundingClientRect().width>30),'Structural thumbnail bars fill their grid cells');
  assert.equal(await page.locator('#library-list iframe').count(),0,'Static thumbnails do not allocate preview frames');
  await page.locator('[data-preview-block="gallery-carousel"]').click();
  const sample=page.frameLocator('#component-preview-frame');
  await sample.locator('.gallery-controls:not([hidden])').waitFor();
  await sample.locator('[data-gallery-step="1"]').click();
  await sample.locator('[data-gallery-track]').evaluate(node=>new Promise(resolve=>{const done=()=>{if(node.scrollLeft>10)resolve();else requestAnimationFrame(done);};done();}));
  await page.locator('[data-component-device="mobile"]').click();
  assert.ok(await sample.locator('body').evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  const artifacts=path.resolve(process.env.FORMA_TEST_ARTIFACTS||'artifacts/interactions');await mkdir(artifacts,{recursive:true});
  await page.screenshot({path:path.join(artifacts,'editor-library.png')});
  await page.locator('[data-close="component-preview-dialog"]').click();
  assert.equal(await page.locator('#component-preview-frame').getAttribute('srcdoc'),null);
  assert.deepEqual((await app.store.get(saved.id)).spec,before.spec,'Library samples never mutate project data');

  const css=await readFile(new URL('../public/site.css',import.meta.url),'utf8');
  const script=(await Promise.all(['site-runtime.js','interface-runtime.js','interaction-runtime.js'].map(name=>readFile(new URL(`../public/${name}`,import.meta.url),'utf8')))).join('\n').replace(/\r\n?/g,'\n');
  const notices=Object.fromEntries(await Promise.all(BUNDLED_NOTICES.map(async name=>[name,await readFile(new URL(`../licenses/${name}.txt`,import.meta.url),'utf8')])));
  const assets={css,script,scriptHash:createHash('sha256').update(script).digest('base64'),notices,originalLicense:await readFile(new URL('../LICENSE',import.meta.url),'utf8')};
  const exported=await browser.newPage({viewport:{width:1280,height:900}});
  exported.on('pageerror',error=>errors.push(error.message));
  const outgoing=[];exported.on('request',request=>{if(/^https?:/.test(request.url()))outgoing.push(request.url());});
  const open=async(current)=>{const files=createExportFiles(current,assets);const filename=path.join(directory,'index.html');await writeFile(filename,files['index.html']);await exported.goto(pathToFileURL(filename).href);};
  await open(spec);
  await exported.locator('[data-gallery-enhanced="stack"]').waitFor();
  const underline=exported.locator('.app-dashboard .ui-button').first();await underline.focus();await exported.waitForTimeout(220);
  assert.ok(await underline.locator('.button-label').evaluate(node=>getComputedStyle(node).textDecorationColor===getComputedStyle(node).color),'Keyboard focus displays the authored underline');
  await exported.locator('.features-spotlight .feature-card').first().hover();
  await exported.locator('[data-spotlight-active="true"]').waitFor();
  await exported.locator('.features-spotlight').scrollIntoViewIfNeeded();
  await exported.locator('[data-entrance-playing="rise"]').waitFor();
  await exported.locator('.gallery-stack').screenshot({path:path.join(artifacts,'components-desktop.png')});
  await exported.evaluate(()=>dispatchEvent(new PageTransitionEvent('pagehide',{persisted:true})));
  await exported.locator('[data-gallery-step="1"]').click();
  assert.equal(await exported.locator('.gallery-position').textContent(),'2 / 3','Cached pages preserve interaction listeners');
  const arrow=exported.locator('.cta-band .site-button,.cta-card .site-button').first();
  await arrow.hover();await exported.waitForTimeout(250);
  assert.notEqual(await arrow.locator('svg').evaluate(node=>getComputedStyle(node).transform),'none');
  await exported.emulateMedia({reducedMotion:'reduce'});
  await exported.locator('[data-gallery-enhanced="plain"]').waitFor();
  assert.equal(await exported.locator('[data-spotlight-active]').count(),0);
  assert.equal(await exported.locator('[data-entrance-playing]').count(),0);
  assert.equal(await exported.locator('[data-scroll-stack="true"]').count(),0);
  await exported.locator('.ui-tabs [role="tab"]').nth(1).click();
  assert.ok(await exported.locator('[data-ui-panel="summary"]').isVisible(),'Reduced motion preserves functional tabs');
  await exported.emulateMedia({reducedMotion:'no-preference'});
  await exported.setViewportSize({width:390,height:844});
  await exported.locator('[data-gallery-enhanced="plain"]').waitFor();
  assert.equal(await exported.locator('[data-gallery-item][inert]').count(),0);
  assert.ok(await exported.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await exported.locator('.gallery-stack').screenshot({path:path.join(artifacts,'components-mobile.png')});
  const long=structuredClone(spec);long.sections[4].items[0].body='Long authored description. '.repeat(60);
  await exported.setViewportSize({width:1000,height:600});long.theme.motion='expressive';await open(long);
  assert.equal(await exported.locator('[data-scroll-stack="true"]').count(),0,'Tall authored content stays sequential');
  long.theme.motion='none';await open(long);
  assert.equal(await exported.locator('[data-scroll-stack="true"]').count(),0);
  assert.equal(await exported.locator('[data-gallery-item][inert]').count(),0);
  await exported.locator('.service-disclosure summary').first().click();assert.ok(await exported.locator('.service-disclosure').first().evaluate(node=>node.open));
  const carousel=structuredClone(spec);carousel.sections=[makeSection('gallery','gallery-carousel')];carousel.theme.motion='none';
  carousel.sections[0].items=Array.from({length:8},(_,index)=>({...carousel.sections[0].items[index%3],id:`gallery-${index}`}));
  await open(carousel);await exported.locator('[data-gallery-step="1"]').click();
  assert.ok(await exported.locator('[data-gallery-track]').evaluate(node=>node.scrollLeft>0));
  await exported.locator('[data-gallery-track]').focus();await exported.keyboard.press('End');
  await exported.waitForTimeout(50);
  assert.equal(await exported.locator('.gallery-position').textContent(),'8 / 8');
  assert.ok(await exported.locator('[data-gallery-step="1"]').isDisabled());
  carousel.sections[0].items=carousel.sections[0].items.slice(0,1);await open(carousel);assert.equal(await exported.locator('.gallery-controls').count(),0);
  carousel.sections[0].items=[];await open(carousel);assert.equal(await exported.locator('[data-gallery-item]').count(),0);
  assert.equal(outgoing.length,0,'Standalone file export makes no network requests');
  assert.deepEqual(errors,[]);
});
